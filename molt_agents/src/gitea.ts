export async function commentPR(
  owner: string,
  repo: string,
  prNumber: number,
  body: string,
) {
  await client(config.reviewerAgentName).post(
    `/repos/${owner}/${repo}/issues/${prNumber}/comments`,
    { body },
  );
}

export async function mergePR(owner: string, repo: string, prNumber: number) {
  await client(config.reviewerAgentName).post(
    `/repos/${owner}/${repo}/pulls/${prNumber}/merge`,
    { Do: "merge" },
  );
}

/**
 * Close an issue by setting its state to "closed"
 */
export async function closeIssue(
  owner: string,
  repo: string,
  issueNumber: number,
) {
  try {
    await client(config.reviewerAgentName).patch(
      `/repos/${owner}/${repo}/issues/${issueNumber}`,
      { state: "closed" },
    );
    console.log(`✅ Issue #${issueNumber} closed in ${owner}/${repo}`);
  } catch (err: any) {
    console.error(
      `❌ Failed to close issue #${issueNumber}:`,
      err.response?.data || err.message,
    );
  }
}

export async function forkRepo(owner: string, repo: string) {
  const agentName = config.builderAgentName;
  const username = agentName;
  const api = client(agentName);

  try {
    // 1️⃣ Check if fork already exists
    try {
      const existingFork = await api.get(`/repos/${username}/${repo}`);
      console.log(`ℹ️ Fork already exists: ${username}/${repo}`);
      return existingFork.data;
    } catch (err: any) {
      if (err.response?.status !== 404) {
        console.error(
          "❌ Error checking existing fork:",
          err.response?.data || err.message,
        );
        return null; // don't crash builder
      }
    }

    // 2️⃣ Create fork
    const res = await api.post(`/repos/${owner}/${repo}/forks`);
    console.log(
      `✅ Fork created: ${owner}/${repo} -> ${res.data.owner.login}/${repo}`,
    );

    return res.data;
  } catch (err: any) {
    console.error("❌ Failed to fork repo:", err.response?.data || err.message);
    return null; // graceful failure
  }
}
