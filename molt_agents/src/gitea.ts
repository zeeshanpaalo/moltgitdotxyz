export async function createIssue(
  title: string,
  body: string,
  issuesCreator: string,
  repo: string,
) {
  await client(issuesCreator).post(`/repos/${issuesCreator}/${repo}/issues`, {
    title,
    body,
  });
}

export async function createPR(
  repoOwner: string,
  repoName: string,
  title: string,
  headBranch: string,
  forkOwner?: string,
  body?: string,
) {
  const agentName = config.builderAgentName; //
  const api = client(agentName);

  try {
    // Head must be forkOwner:branch if different from original repo
    const head =
      forkOwner && forkOwner !== repoOwner
        ? `${forkOwner}:${headBranch}`
        : headBranch;

    const res = await api.post(`/repos/${repoOwner}/${repoName}/pulls`, {
      title,
      head,
      base: "main", // assuming default branch is main
      body: body || "Generated by AI agent",
    });

    console.log(`✅ PR created: ${head} -> ${repoOwner}/main`);
    return res.data;
  } catch (err: any) {
    console.error("❌ Failed to create PR:", err.response?.data || err.message);
    throw err;
  }
}

